"""Write Sources/PaperhueAgenda/ICal/ZoneTables.swift: the zone names the iCal reader knows, as
the Python reference (python/src/ulani_epaper/ical.py with icalendar) knows them.

- The Windows zone names icalendar maps to IANA names (icalendar.timezone.windows_to_olson,
  from CLDR's windowsZones.xml).
- zoneinfo.available_timezones(): the IANA names zoneinfo loads, which icalendar also uses to
  decide that a VTIMEZONE needs no definition of its own.

Run with the reference environment: python make_zone_tables.py
"""

import zoneinfo
from pathlib import Path

from icalendar.timezone import windows_to_olson

OUT = Path(__file__).resolve().parents[3] / "Sources" / "PaperhueAgenda" / "ICal" / "ZoneTables.swift"


def quoted(s: str) -> str:
    assert s.isascii() and '"' not in s and "\\" not in s
    return f'"{s}"'


def main() -> None:
    mapping = windows_to_olson.WINDOWS_TO_OLSON
    keys = sorted(zoneinfo.available_timezones())
    lines = [
        "// Generated by Tests/PaperhueAgendaTests/Differential/make_zone_tables.py; do not edit.",
        f"// Windows names: CLDR windowsZones.xml {windows_to_olson.version_date}, as icalendar maps them.",
        "",
        "enum ZoneTables {",
        "    /// Windows zone name -> IANA name.",
        "    static let windowsToIANA: [String: String] = [",
        *(f"        {quoted(k)}: {quoted(v)}," for k, v in sorted(mapping.items())),
        "    ]",
        "",
        "    /// zoneinfo.available_timezones().",
        "    static let ianaNames: Set<String> = [",
        *("        " + " ".join(quoted(k) + "," for k in keys[i:i + 4]) for i in range(0, len(keys), 4)),
        "    ]",
        "}",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT}: {len(mapping)} Windows names, {len(keys)} IANA names")


if __name__ == "__main__":
    main()
